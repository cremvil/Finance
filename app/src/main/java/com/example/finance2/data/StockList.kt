    private fun createStock(
        index: Int,
        ticker: String,
        name: String,
        priceValue: Double,
        changeText: String,
        isPositive: Boolean,
        bgColor: Long
    ): Stock {
        val formattedPrice = if (priceValue >= 1.0) {
            String.format(java.util.Locale.forLanguageTag("ru-RU"), "%.2f ₽", priceValue)
        } else {
            String.format(java.util.Locale.forLanguageTag("ru-RU"), "%.4f ₽", priceValue)
        }

        return Stock(
            id = "stock_$index",
            name = name,
            ticker = ticker,
            priceText = formattedPrice,
            priceValue = priceValue,
            changePercentText = changeText,
            isPositive = isPositive,
            logoText = if (ticker.length >= 2) ticker.take(2) else ticker,
            logoBgColor = bgColor,
            holdingValueText = null,
            isHolding = false
        )
    }
